"""教材习题组 → 节 的映射。

为什么不能只按「组序号 = 节序号」硬对：第 12 章 12 节只有 5 个习题组，
一组跨 2–3 节。组的页范围能证明它覆盖哪几节（教材页），组内再用判别词定到具体节。

第 12 章页证据（教材页 = PDF 页 - 9）：
    12-1 p83  → 12.1 p74 / 12.2 p75 / 12.3 p81（12.4 在 p84，故止于 12.3）
    12-2 p92  → 12.4 p84 / 12.5 p86（12.6 在 p95）
    12-3 p103 → 12.6 p95 / 12.7 p101（12.8 在 p106）
    12-4 p116 → 12.8 p106 / 12.9 p112 / 12.10 p113（12.11 在 p120）
    12-5 p124 → 12.11 p120 / 12.12 p123
其余章组数与节数相等，直接一一对应（见 ingest 的 GROUP_TO_SEC）。
"""
import re

# 每组可能覆盖的节，顺序即同分时的优先顺序
GROUP_CANDS = {
    "12-1": ["12.1", "12.2", "12.3"],
    "12-2": ["12.4", "12.5"],
    "12-3": ["12.6", "12.7"],
    "12-4": ["12.8", "12.9", "12.10"],
    "12-5": ["12.11", "12.12"],
}

# 判别词 → 权重。权重 3 是「几乎只在讲这一节」的词，1 是弱信号。
SEC_HINTS = {
    "12.1": [("三角形", 1), ("三边", 1), ("稳定", 3), ("按角", 3), ("按边", 3), ("三条线段", 2), ("图中有", 1)],
    "12.2": [("内角和", 3), ("外角", 3), ("两边之和", 3), ("取值范围", 2), ("第三边", 2), ("周长", 1),
             ("求∠", 2), ("度数", 2), ("∠A", 1), ("∠B", 1), ("∠C", 1), ("延长", 1), ("平分", 1)],
    "12.3": [("中线", 3), ("角平分线", 3), ("高", 2), ("重心", 3), ("线段", 1)],
    "12.4": [("全等", 1), ("对应边", 3), ("对应角", 3), ("重合", 2)],
    "12.5": [("SSS", 3), ("SAS", 3), ("ASA", 3), ("AAS", 3), ("HL", 3), ("判定", 3),
             ("求证", 2), ("证明", 2), ("≌", 3)],
    "12.6": [("等腰", 3), ("等边", 3), ("底边", 2), ("顶角", 2), ("底角", 2), ("三线合一", 3)],
    "12.7": [("Rt△", 3), ("直角三角", 3), ("斜边", 2), ("90°", 2), ("∠ACB", 1), ("30°", 1)],
    "12.8": [("尺规", 3), ("作图", 3), ("痕迹", 3), ("画一个", 2), ("画图", 2)],
    "12.9": [("逆命题", 3), ("逆定理", 1), ("命题", 2), ("真假", 2)],
    "12.10": [("轴对称", 3), ("对称轴", 3), ("垂直平分线", 3), ("对称点", 3), ("折叠", 2), ("对称图形", 3)],
    "12.11": [("勾股定理", 3), ("斜边", 1), ("平方", 1), ("较长直角边", 2)],
    "12.12": [("勾股定理的逆", 5), ("逆定理", 3), ("是直角三角形", 3), ("判断", 2), ("三边", 2), ("平方关系", 2)],
}


def score(sec, stem):
    s = 0
    for w, k in SEC_HINTS.get(sec, []):
        if w in stem:
            s += k * stem.count(w)
    return s


# 只有强信号（得分 >= STRONG）才归到具体节；否则落章末虚拟节。
# 试过「无信号时落到组的主节」，结果 12-2 组 20 题里 18 题被塞进 12.4（全等三角形），
# 而这些题实际是等腰、全等判定、轴对称——归错节比不归节更糟：孩子按节练会练到不相关的题。
STRONG = 3


def sec_of(group, stem):
    """返回该题应落的节号，落不到返回 None（调用方落章末虚拟节）。"""
    cands = GROUP_CANDS.get(group)
    if not cands:
        return None
    best, best_s = None, 0
    for sec in cands:                     # 同分时保留更靠前的节
        sc = score(sec, stem or "")
        if sc > best_s:
            best, best_s = sec, sc
    if best is None or best_s < STRONG:
        return None
    return best
